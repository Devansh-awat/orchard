import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = resolve(packageRoot, '../../apps/server/test/auth-coverage.snapshot.json');
const scopeSnapshotPath = resolve(packageRoot, '../../apps/server/test/auth-scope.snapshot.json');
const outputPath = resolve(packageRoot, 'src/routes.generated.ts');

const snapshot: Record<string, string> = JSON.parse(readFileSync(snapshotPath, 'utf8'));
const scopes: Record<string, string> = JSON.parse(readFileSync(scopeSnapshotPath, 'utf8'));

for (const [key, scope] of Object.entries(scopes)) {
  if (!(key in snapshot)) throw new Error(`scope snapshot lists an unknown route: ${key}`);
  if (!['read', 'deploy', 'exec'].includes(scope)) {
    throw new Error(`unexpected scope in snapshot: ${key} -> ${scope}`);
  }
}

const entries = Object.entries(snapshot)
  .map(([key, auth]) => {
    const spaceIndex = key.indexOf(' ');
    const method = key.slice(0, spaceIndex);
    const path = key.slice(spaceIndex + 1);
    if (!['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'ALL'].includes(method)) {
      throw new Error(`unexpected method in snapshot: ${key}`);
    }
    if (!['public', 'authenticated', 'superadmin'].includes(auth)) {
      throw new Error(`unexpected auth level in snapshot: ${key} -> ${auth}`);
    }
    return { method, path, auth, scope: scopes[key] };
  })
  .sort((a, b) =>
    a.path === b.path ? a.method.localeCompare(b.method) : a.path.localeCompare(b.path)
  );

const lines = entries.map((route) => {
  const scope = route.scope ? `, requiredScope: '${route.scope}'` : '';
  return `  { method: '${route.method}', path: '${route.path}', auth: '${route.auth}'${scope} },`;
});

const banner =
  '// generated by scripts/bootstrap.ts from apps/server/test/auth-coverage.snapshot.json and auth-scope.snapshot.json — do not edit by hand';

const output = `${banner}
import type { GeneratedRoute } from './types';

export const routes: GeneratedRoute[] = [
${lines.join('\n')}
];
`;

writeFileSync(outputPath, output);
console.log(`wrote ${entries.length} routes to ${outputPath}`);
