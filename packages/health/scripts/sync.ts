import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..', '..', '..');
const source = readFileSync(resolve(root, 'packages/health/src/health.ts'), 'utf8');
const target = resolve(root, 'apps/server/src/health/health.generated.ts');
writeFileSync(
  target,
  `// generated by packages/health/scripts/sync.ts from packages/health/src/health.ts, do not edit by hand\n${source}`
);
console.log(`wrote ${target}`);
