	interface IngressRoute {
		path: string;
		serviceName: string;
		servicePort: number;
	}

	interface ServicePort {
		name?: string;
		port: number;
		targetPort: number;
		protocol: string;
	}

	interface Service {
		id: string;
		name: string;
		port: number;
		targetPort: number;
		protocol: string;
		ports?: ServicePort[];
	}

	interface Deployment {
		id: string;
		name: string;
		services?: Service[];
	}

	interface Ingress {
		id: string;
		name: string;
		namespace: string;
		host: string;
		path: string;
		pathType: string;
		tlsEnabled: boolean;
		tlsSecretName?: string;
		address?: string;
		statusAddress?: string;
		annotations?: Record<string, any>;
		routes?: IngressRoute[];
		entrypoints?: string[];
		clusterIssuer?: string;
		deployment?: {
			id: string;
			name: string;
		} | null;
		service?: {
			id: string;
			name: string;
			port: number;
		} | null;
		project: {
			id: string;
			name: string;
			slug: string;
			workspace: {
				id: string;
				name: string;
				slug: string;
			};
			deployments?: Deployment[];
		};
	}

	type ServiceOption = {
		key: string;
		label: string;
		deploymentId: string;
		serviceName: string;
		port: number;
	};

	type IngressFormEntry = {
		id: string;
		deploymentId: string;
		host: string;
		path: string;
		serviceKey: string;
		tlsEnabled: boolean;
		dnsValidated?: boolean;
		dnsValidating?: boolean;
		dnsError?: string;
		autoGenerated?: boolean;
		basicAuthEnabled: boolean;
		basicAuthUsername: string;
		basicAuthPassword: string;
		basicAuthShowPassword: boolean;
	};

	const tabSections = [
		{
			id: 'overview',
			label: 'Overview',
			description: 'Ingress details',
			icon: Globe
		},
		{
			id: 'settings',
			label: 'Settings',
			description: 'Edit configuration',
			icon: Settings
		},
		{
			id: 'danger',
			label: 'Danger Zone',
			description: 'Delete ingress',
			icon: Shield
		}
	] as const;

	type TabId = (typeof tabSections)[number]['id'];

	const tabs = new Tabs<TabId>({
		value: 'overview',
		loop: true
	});

	const ingressId = $derived($page.params.id);
	const orgSlug = $derived($page.params.orgSlug);

	let ingress = $state<Ingress | null>(null);
	let loading = $state(true);
	let error = $state<string | null>(null);
	let deleting = $state(false);

	// Settings tab state
	let ingressEntries = $state<IngressFormEntry[]>([]);
	let submitting = $state(false);
	let formError = $state<string | null>(null);
	let serviceDropdownOpen = $state<string | null>(null);
	let originalBasicAuthEnabled = $state(false);
	let showDnsModal = $state(false);
	let dnsModalEntryIndex = $state<number | null>(null);

	const hasBasicAuth = $derived(
		ingress?.annotations?.['traefik.ingress.kubernetes.io/router.middlewares']?.includes('auth@kubernetescrd')
	);

	// Derive linked deployments from routes' service names matched against project deployments
	const linkedDeployments = $derived.by(() => {
		if (!ingress?.routes?.length || !ingress?.project?.deployments?.length) return [];
		const routeServiceNames = new Set(ingress.routes.map((r) => r.serviceName));
		const seen = new Set<string>();
		const result: Array<{ id: string; name: string }> = [];
		for (const dep of ingress.project.deployments) {
			if (seen.has(dep.id)) continue;
			for (const svc of dep.services ?? []) {
				if (routeServiceNames.has(svc.name)) {
					seen.add(dep.id);
					result.push({ id: dep.id, name: dep.name });
					break;
				}
			}
		}
		return result;
	});

	const generateEntryId = () => {
		if (typeof crypto !== 'undefined' && crypto.randomUUID) {
			return crypto.randomUUID();
		}
		return Math.random().toString(36).slice(2);
	};

	const generateRandomDomain = (): string => {
		const chars = 'abcdefghijklmnopqrstuvwxyz0123456789';
		let randomPart = '';
		for (let i = 0; i < 6; i++) {
			randomPart += chars.charAt(Math.floor(Math.random() * chars.length));
		}
		return `${randomPart}.a.lfdl.ink`;
	};

	const createIngressEntry = (overrides?: Partial<IngressFormEntry>): IngressFormEntry => ({
		id: generateEntryId(),
		deploymentId: '',
		host: '',
		path: '/',
		serviceKey: '',
		tlsEnabled: true,
		dnsValidated: false,
		dnsValidating: false,
		dnsError: undefined,
		basicAuthEnabled: false,
		basicAuthUsername: '',
		basicAuthPassword: '',
		basicAuthShowPassword: false,
		...overrides
	});

	function getAllServiceOptions(): ServiceOption[] {
		const deployments = ingress?.project?.deployments ?? [];
		const options: ServiceOption[] = [];
		for (const deployment of deployments) {
			for (const s of deployment.services ?? []) {
				options.push({
					key: `${deployment.id}::${s.id}::${s.port}`,
					label: `${deployment.name} » ${s.name} - ${s.port} -> ${s.targetPort} ${s.protocol}`,
					deploymentId: deployment.id,
					serviceName: s.name,
					port: s.port
				});
			}
		}
		return options;
	}

	function updateEntry(index: number, updates: Partial<IngressFormEntry>) {
		ingressEntries = ingressEntries.map((entry, idx) => {
			if (idx === index) {
				const updated = { ...entry, ...updates };
				if (updates.host !== undefined && updates.host !== entry.host) {
					updated.dnsValidated = false;
					updated.dnsError = undefined;
					if (!updated.host.endsWith('.a.lfdl.ink')) {
						updated.autoGenerated = false;
					}
				}
				return updated;
			}
			return entry;
		});
	}

	function generateDomainForEntry(index: number) {
		updateEntry(index, {
			host: generateRandomDomain(),
			autoGenerated: true,
			dnsValidated: true,
			dnsError: undefined
		});
	}

	async function validateDns(index: number) {
		const entry = ingressEntries[index];
		if (!entry?.host?.trim()) return;

		updateEntry(index, { dnsValidating: true, dnsError: undefined });

		try {
			const response = await apiFetch(`/apiv1/projects/ingresses/validate-dns`, {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify({ domain: entry.host.trim() })
			});

			if (!response.ok) throw new Error('Failed to validate DNS');
			const result = await response.json();

			if (result.valid) {
				updateEntry(index, { dnsValidated: true, dnsValidating: false, dnsError: undefined });
			} else {
				updateEntry(index, { dnsValidated: false, dnsValidating: false, dnsError: result.message });
			}
		} catch (e) {
			updateEntry(index, {
				dnsValidated: false,
				dnsValidating: false,
				dnsError: e instanceof Error ? e.message : 'Failed to validate DNS'
			});
		}
	}

	function openDnsModal(index: number) {
		dnsModalEntryIndex = index;
		showDnsModal = true;
	}

	function closeDnsModal() {
		showDnsModal = false;
		dnsModalEntryIndex = null;
	}

	function handleServiceChange(index: number, serviceKey: string) {
		const option = getAllServiceOptions().find((o) => o.key === serviceKey);
		if (option) {
			updateEntry(index, { deploymentId: option.deploymentId, serviceKey: option.key });
		}
	}

	function addIngressEntry() {
		const lastEntry = ingressEntries.at(-1);
		const lastHost = lastEntry?.host ?? '';
		const allOptions = getAllServiceOptions();
		const defaultOption = lastEntry?.serviceKey
			? allOptions.find((o) => o.key === lastEntry.serviceKey) ?? allOptions[0]
			: allOptions[0];
		ingressEntries = [
			...ingressEntries,
			createIngressEntry({
				host: lastHost,
				deploymentId: defaultOption?.deploymentId ?? '',
				serviceKey: defaultOption?.key ?? ''
			})
		];
	}

	function removeIngressEntry(index: number) {
		if (ingressEntries.length === 1) return;
		ingressEntries = ingressEntries.filter((_, idx) => idx !== index);
	}

	function resolveServiceSelection(entry: IngressFormEntry) {
		if (!entry.serviceKey) return null;
		return getAllServiceOptions().find((option) => option.key === entry.serviceKey) ?? null;
	}

	function populateFormFromIngress() {
		if (!ingress) return;

		originalBasicAuthEnabled = hasBasicAuth ?? false;
		const allOptions = getAllServiceOptions();

		const entries: IngressFormEntry[] = (ingress.routes || []).map((route) => {
			const matchingOption = allOptions.find(
				(o) => o.serviceName === route.serviceName && o.port === route.servicePort
			);
			const isAutoGenerated = ingress!.host.endsWith('.a.lfdl.ink');
			return createIngressEntry({
				host: ingress!.host,
				path: route.path,
				deploymentId: matchingOption?.deploymentId ?? '',
				serviceKey: matchingOption?.key ?? '',
				tlsEnabled: ingress!.tlsEnabled ?? true,
				dnsValidated: true,
				autoGenerated: isAutoGenerated,
				basicAuthEnabled: hasBasicAuth ?? false,
				basicAuthUsername: '',
				basicAuthPassword: ''
			});
		});

		ingressEntries = entries.length > 0 ? entries : [createIngressEntry()];
	}

	async function fetchIngress() {
		loading = true;
		error = null;

		try {
			const response = await apiFetch(`/apiv1/ingresses/${ingressId}`);
			if (!response.ok) throw new Error('Failed to fetch ingress');
			ingress = await response.json();
			populateFormFromIngress();
		} catch (e) {
			error = e instanceof Error ? e.message : 'Failed to load ingress';
		} finally {
			loading = false;
		}
	}

	async function saveSettings() {
		if (!ingress) return;

		if (!ingressEntries.length) {
			formError = 'Add at least one ingress route';
			return;
		}

		const normalizedEntries = [];

		for (let index = 0; index < ingressEntries.length; index += 1) {
			const entry = ingressEntries[index];
			const label = `Route ${index + 1}`;

			const serviceSelection = resolveServiceSelection(entry);
			if (!serviceSelection) {
				formError = `${label}: Select a service`;
				return;
			}

			const host = entry.host.trim().toLowerCase();
			if (!host) {
				formError = `${label}: Domain is required`;
				return;
			}

			let normalizedPath = entry.path.trim() || '/';
			if (!normalizedPath.startsWith('/')) {
				normalizedPath = `/${normalizedPath}`;
			}

			normalizedEntries.push({
				label,
				deploymentId: serviceSelection.deploymentId,
				body: {
					host,
					path: normalizedPath,
					serviceName: serviceSelection.serviceName,
					servicePort: serviceSelection.port,
					tlsEnabled: entry.tlsEnabled
				}
			});
		}

		const uniqueHosts = [...new Set(normalizedEntries.map((e) => e.body.host))];
		if (uniqueHosts.length > 1) {
			formError = 'All routes must use the same host to create a single ingress';
			return;
		}

		const hasUnvalidatedDns = ingressEntries.some(
			(e) => !e.autoGenerated && e.host.trim() && !e.dnsValidated
		);
		if (hasUnvalidatedDns && !confirm(
			'Some domains have not been verified. Ensure your CNAME records are configured or TLS may fail. Update anyway?'
		)) {
			return;
		}

		if (ingressEntries[0].basicAuthEnabled) {
			const hasNewCredentials = ingressEntries[0].basicAuthUsername.trim() || ingressEntries[0].basicAuthPassword.trim();
			if (!originalBasicAuthEnabled || hasNewCredentials) {
				if (!ingressEntries[0].basicAuthUsername.trim()) {
					formError = 'Basic auth username is required';
					return;
				}
				if (!ingressEntries[0].basicAuthPassword.trim()) {
					formError = 'Basic auth password is required';
					return;
				}
			}
		}

		submitting = true;
		formError = null;

		const first = normalizedEntries[0];
		const firstFormEntry = ingressEntries[0];

		let basicAuth: { enabled: boolean; username: string; password: string } | undefined;
		if (firstFormEntry.basicAuthEnabled) {
			if (firstFormEntry.basicAuthUsername.trim() && firstFormEntry.basicAuthPassword.trim()) {
				basicAuth = {
					enabled: true,
					username: firstFormEntry.basicAuthUsername,
					password: firstFormEntry.basicAuthPassword
				};
			} else if (originalBasicAuthEnabled) {
				basicAuth = undefined;
			} else {
				basicAuth = {
					enabled: true,
					username: firstFormEntry.basicAuthUsername,
					password: firstFormEntry.basicAuthPassword
				};
			}
		} else {
			basicAuth = { enabled: false, username: '', password: '' };
		}

		const body = {
			host: first.body.host,
			tlsEnabled: first.body.tlsEnabled,
			routes: normalizedEntries.map((e) => ({
				path: e.body.path,
				serviceName: e.body.serviceName,
				servicePort: e.body.servicePort
			})),
			basicAuth
		};

		try {
			const response = await apiFetch(`/apiv1/projects/${ingress.project.id}/ingresses/${ingressId}`, {
				method: 'PUT',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify(body)
			});

			if (!response.ok) {
				const data = await response.json().catch(() => ({}));
				throw new Error(data.message || 'Failed to update ingress');
			}

			toasts.add({
				title: 'Ingress updated',
				description: `Updated ingress with ${normalizedEntries.length} route(s)`,
				color: 'success'
			});

			await fetchIngress();
			tabs.value = 'overview';
		} catch (e) {
			formError = e instanceof Error ? e.message : 'Failed to update ingress';
		} finally {
			submitting = false;
		}
	}

	async function deleteIngress() {
		if (!ingress) return;
		if (!confirm('Are you sure you want to delete this ingress? This cannot be undone.')) return;

		deleting = true;

		try {
			// Use deployment-level delete if linked, otherwise project-level
			const deploymentId = ingress.deployment?.id;
			let url: string;
			if (deploymentId) {
				url = `/apiv1/deployments/${deploymentId}/ingresses/${ingressId}`;
			} else {
				// Fall back to project-level endpoint
				url = `/apiv1/projects/${ingress.project.id}/ingresses/${ingressId}`;
			}

			const response = await apiFetch(url, { method: 'DELETE' });
			if (!response.ok) throw new Error('Failed to delete ingress');

			toasts.add({ title: 'Ingress deleted', color: 'success' });
			refreshTree();
			goto(`/${orgSlug}/workspaces/${ingress.project.workspace.slug}/projects/${ingress.project.slug}`);
		} catch (e) {
			toasts.add({
				title: 'Error',
				description: e instanceof Error ? e.message : 'Failed to delete ingress',
				color: 'error'
			});
		} finally {
			deleting = false;
		}
	}

	$effect(() => {
		// Re-fetch when ingressId changes (reactive to param)
		ingressId;
		fetchIngress();
	});

	onMount(() => {
		function handleClickOutside(event: MouseEvent) {
			const target = event.target as HTMLElement;
			if (!target.closest('.service-dropdown-container')) {
				serviceDropdownOpen = null;
			}
		}
		document.addEventListener('click', handleClickOutside);
		return () => document.removeEventListener('click', handleClickOutside);
	});
</script>

