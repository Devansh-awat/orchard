			<div class="card space-y-6 p-6">

				{#if !(project.deployments?.length)}
					<div class="alert alert-warning">
						Create a deployment for this project before configuring ingresses.
					</div>
				{:else}
					<div class="space-y-6">
						{#each ingressEntries as entry, index (entry.id)}
							{@const serviceOptions = getAllServiceOptions()}
							<div class="surface-form rounded-2xl border border-dashed p-4">
								<div class="mb-4 flex flex-wrap items-center justify-between gap-3">
									<div>
										<p class="font-semibold" style="color: var(--center-channel-color);">Route {index + 1}</p>
										<p class="text-sm" style="color: color-mix(in srgb, var(--center-channel-color) 70%, transparent);">Select the service, domain (same for all routes), and path.</p>
									</div>
									{#if ingressEntries.length > 1}
										<button
											type="button"
											onclick={() => removeIngressEntry(index)}
											class="btn btn-ghost btn-sm text-red-500"
										>
											<Trash2 class="h-4 w-4" />
											Remove
										</button>
									{/if}
								</div>

								<div class="grid gap-4 md:grid-cols-2">
									<div>
										<label class="mb-2 block text-sm font-medium">
											<span class="inline-block">Domain</span>
											<button
												type="button"
												onclick={() => openDnsModal(index)}
												class="ml-2 inline-flex items-center gap-1 text-xs align-middle h-5 px-2 rounded hover:opacity-80 transition-opacity"
												style="color: var(--link-color);"
											>
												<Info class="h-3 w-3" />
												How to configure DNS
											</button>
										</label>
										<div class="flex gap-2">
											<input
												type="text"
												class="input flex-1"
												placeholder="example.com"
												value={entry.host}
												oninput={(event) =>
													updateEntry(index, { host: (event.currentTarget as HTMLInputElement).value })}
											/>
											{#if !entry.host.trim()}
												<button
													type="button"
													onclick={() => generateDomainForEntry(index)}
													class="btn btn-sm btn-secondary"
													title="Generate random domain"
												>
													<RefreshCw class="h-4 w-4" />
													Auto-generate
												</button>
											{:else if !entry.autoGenerated}
												<button
													type="button"
													onclick={() => validateDns(index)}
													class="btn btn-sm {entry.dnsValidated ? '' : 'btn-secondary'}"
													style={entry.dnsValidated ? 'background-color: #33d6a6; color: white;' : ''}
													disabled={entry.dnsValidating}
												>
													{#if entry.dnsValidating}
														<Loader2 class="h-4 w-4 animate-spin" />
													{:else if entry.dnsValidated}
														<CheckCircle2 class="h-4 w-4" />
													{:else}
														<RefreshCw class="h-4 w-4" />
													{/if}
													Verify DNS
												</button>
											{/if}
										</div>
										{#if entry.dnsError}
											<p class="mt-1 text-xs" style="color: var(--error-text-color);">{entry.dnsError}</p>
										{/if}
										{#if entry.autoGenerated}
											<p class="mt-1 text-xs" style="color: #33d6a6;">Auto-generated domain ready to use</p>
										{:else if entry.dnsValidated}
											<p class="mt-1 text-xs" style="color: #33d6a6;">DNS validated successfully</p>
										{/if}
									</div>

									<div>
										<label class="mb-2 block text-sm font-medium">Path</label>
										<input
											type="text"
											class="input"
											placeholder="/ or /api"
											value={entry.path}
											oninput={(event) =>
												updateEntry(index, { path: (event.currentTarget as HTMLInputElement).value })}
										/>
										<p class="mt-1 text-xs" style="color: color-mix(in srgb, var(--center-channel-color) 70%, transparent);">Paths should start with a slash.</p>
									</div>

									<div class="md:col-span-2">
										<label class="mb-2 block text-sm font-medium">Service</label>
										{#if serviceOptions.length}
											<div class="relative service-dropdown-container">
												<button
													type="button"
													onclick={() => (serviceDropdownOpen = serviceDropdownOpen === entry.id ? null : entry.id)}
													class="flex w-full items-center justify-between overflow-hidden rounded-xl border px-3 py-2 text-sm transition"
													style="background-color: var(--control-bg); color: var(--center-channel-color); border-color: var(--surface-border);"
												>
													<span>
														{serviceOptions.find((opt) => opt.key === entry.serviceKey)?.label || 'Select service'}
													</span>
													<ChevronDown class="h-4 w-4 shrink-0" />
												</button>
												{#if serviceDropdownOpen === entry.id}
													<div
														class="absolute z-20 mt-1 w-full rounded-xl border p-2 shadow max-h-60 overflow-y-auto"
														style="background-color: var(--surface-bg); border-color: var(--surface-border); color: var(--center-channel-color);"
														transition:scale={{ duration: 150, start: 0.96 }}
													>
														<button
															type="button"
															onclick={() => {
																updateEntry(index, { deploymentId: '', serviceKey: '' });
																serviceDropdownOpen = null;
															}}
															class="flex w-full items-center justify-between rounded-lg px-3 py-2 text-left text-sm transition hover:bg-[color-mix(in_srgb,var(--surface-border)_40%,transparent)]"
														>
															<span>Select service</span>
															{#if !entry.serviceKey}
																<Check class="h-4 w-4 text-primary-600" />
															{/if}
														</button>
														{#each serviceOptions as option}
															<button
																type="button"
																onclick={() => {
																	handleServiceChange(index, option.key);
																	serviceDropdownOpen = null;
																}}
																class="flex w-full items-center justify-between rounded-lg px-3 py-2 text-left text-sm transition hover:bg-[color-mix(in_srgb,var(--surface-border)_40%,transparent)]"
															>
																<span>{option.label}</span>
																{#if entry.serviceKey === option.key}
																	<Check class="h-4 w-4 text-primary-600" />
																{/if}
															</button>
														{/each}
													</div>
												{/if}
											</div>
										{:else}
											<div class="surface-muted-panel rounded-xl px-3 py-2 text-sm">
												This project has no services yet. Create a deployment with services first.
											</div>
										{/if}
									</div>

									<div class="md:col-span-2">
										<label class="surface-checkbox flex items-center gap-3 rounded-2xl px-3 py-2 text-sm">
												<input
													type="checkbox"
													checked={entry.tlsEnabled}
													onchange={(event) =>
														updateEntry(index, {
															tlsEnabled: (event.currentTarget as HTMLInputElement).checked
														})}
												/>
											<span>
												<span class="font-medium" style="color: var(--center-channel-color);">Enable TLS</span>
												<span class="mt-0.5 block text-xs" style="color: color-mix(in srgb, var(--center-channel-color) 70%, transparent);">
													Automatically provisions a cert-manager certificate with letsencrypt-prod
												</span>
											</span>
										</label>
									</div>

									<div class="md:col-span-2">
										<label class="surface-checkbox flex items-center gap-3 rounded-2xl px-3 py-2 text-sm">
												<input
													type="checkbox"
													checked={entry.basicAuthEnabled}
													onchange={(event) =>
														updateEntry(index, {
															basicAuthEnabled: (event.currentTarget as HTMLInputElement).checked
														})}
												/>
											<span>
												<span class="font-medium" style="color: var(--center-channel-color);">
													<Lock class="inline h-3 w-3 mr-1" />
													Enable Basic Authentication
												</span>
												<span class="mt-0.5 block text-xs" style="color: color-mix(in srgb, var(--center-channel-color) 70%, transparent);">
													Require username and password to access this ingress
												</span>
											</span>
										</label>

										{#if entry.basicAuthEnabled}
											<div class="mt-3 grid gap-3 md:grid-cols-2">
												<div>
													<label class="mb-2 block text-xs font-medium">Username</label>
													<input
														type="text"
														class="input"
														placeholder="admin"
														value={entry.basicAuthUsername}
														oninput={(event) =>
															updateEntry(index, { basicAuthUsername: (event.currentTarget as HTMLInputElement).value })}
													/>
												</div>
												<div>
													<label class="mb-2 block text-xs font-medium">Password</label>
													<div class="relative">
														<input
															type={entry.basicAuthShowPassword ? 'text' : 'password'}
															class="input pr-10"
															placeholder="••••••••"
															value={entry.basicAuthPassword}
															oninput={(event) =>
																updateEntry(index, { basicAuthPassword: (event.currentTarget as HTMLInputElement).value })}
														/>
														<button
															type="button"
															class="absolute right-2 top-1/2 -translate-y-1/2 p-1 hover:opacity-70"
															onclick={() => updateEntry(index, { basicAuthShowPassword: !entry.basicAuthShowPassword })}
														>
															{#if entry.basicAuthShowPassword}
																<EyeOff class="h-4 w-4" />
															{:else}
																<Eye class="h-4 w-4" />
															{/if}
														</button>
													</div>
												</div>
											</div>
										{/if}
									</div>
								</div>
							</div>
						{/each}
					</div>

					<button type="button" class="btn btn-secondary" onclick={addIngressEntry}>
						<Plus class="h-4 w-4" />
						Add another route
					</button>

					{#if formError}
						<div class="alert alert-error">{formError}</div>
