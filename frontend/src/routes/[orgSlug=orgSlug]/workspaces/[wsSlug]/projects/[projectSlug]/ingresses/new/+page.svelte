		<ArrowLeft class="h-4 w-4" />
		Back to project
	</button>

	{#if error}
		<div class="alert alert-error mb-6">{error}</div>
	{/if}

	{#if loading}
		<div class="flex justify-center py-12">
			<Loader2 class="h-8 w-8 animate-spin text-primary-600" />
		</div>
	{:else if project}
		<div class="mx-auto max-w-3xl">
