<script lang="ts">
	import { onMount } from 'svelte';
	import { goto } from '$app/navigation';
	import { fly } from 'svelte/transition';
	import {
		pendingInvitations,
		organizations,
		selectedOrganization,
		user,
		apiFetch,
		toasts
	} from '$lib/stores';
	import {
		Loader2,
		User,
		Github,
		ArrowRight,
		ArrowLeft,
		Check,
		Link2,
		PartyPopper
	} from 'lucide-svelte';

	type Step = 'loading' | 'profile' | 'github' | 'done';

	let currentStep = $state<Step>('loading');
	let orgName = $state('');
	let firstName = $state('');
	let lastName = $state('');
	let username = $state('');
	let saving = $state(false);
	let githubLinked = $state(false);
	let checkingGithub = $state(true);
	let githubUsername = $state<string | null>(null);
	let initialized = $state(false);

	const currentUser = $derived($user);

	function isAutoGeneratedName(name: string, email?: string, uname?: string): boolean {
		if (!name) return false;
		const emailPrefix = email?.split('@')[0] || '';
		return name === emailPrefix || name === uname || name.includes('+') || name.includes('@');
	}

	$effect(() => {
		if (currentUser && !initialized) {
			const fn = currentUser.firstName || '';
			firstName = isAutoGeneratedName(fn, currentUser.email, currentUser.username) ? '' : fn;
			lastName = currentUser.lastName || '';
			username = currentUser.username || '';
			initialized = true;
		}
	});

	onMount(async () => {
		let invitations = [...$pendingInvitations];
		if (invitations.length === 0) {
			invitations = await pendingInvitations.fetchPending();
		}

		if (invitations.length > 0) {
			orgName = invitations[0].organization.name;
		}

		if (!orgName) {
			const orgs = $organizations;
			if (orgs.length > 0) {
				orgName = orgs[0].name;
			}
		}

		// Returning from the GitHub OAuth round-trip lands back on /setup with
		// ?github=linked — resume on the GitHub step instead of restarting.
		const params = new URLSearchParams(window.location.search);
		if (params.get('github') === 'linked' || params.get('step') === 'github') {
			currentStep = 'github';
			checkGitHubStatus();
		} else {
			currentStep = 'profile';
		}
	});

	async function checkGitHubStatus() {
		checkingGithub = true;
		try {
			const response = await apiFetch('/apiv1/github/status');
			if (response.ok) {
				const data = await response.json();
				githubLinked = data.linked;
				githubUsername = data.username || null;
			}
		} catch (e) {
			console.error('Failed to check GitHub status:', e);
		} finally {
			checkingGithub = false;
		}
	}

	async function handleProfileSave() {
		saving = true;

		try {
			const fn = firstName.trim();
			const ln = lastName.trim();
			const un = username.trim();
			const cleanFirstName = isAutoGeneratedName(fn, currentUser?.email, currentUser?.username) ? null : (fn || null);
			const cleanLastName = ln || null;

			const payload = {
				firstName: cleanFirstName,
				lastName: cleanLastName,
				username: un || undefined
			};
			console.log('[Setup] Continue clicked. Form values:', { firstName: fn, lastName: ln, username: un });
			console.log('[Setup] Sending PATCH payload:', JSON.stringify(payload));

			const response = await apiFetch('/apiv1/auth/me', {
				method: 'PATCH',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify(payload)
			});

			const updatedUser = await response.json();
			console.log('[Setup] PATCH response:', response.status, JSON.stringify(updatedUser));

			if (!response.ok) throw new Error('Failed to update profile');

			user.set({ ...$user, ...updatedUser });

			currentStep = 'github';
			await checkGitHubStatus();
		} catch (e) {
			toasts.add({
				title: 'Error',
				description: e instanceof Error ? e.message : 'Failed to update profile',
				color: 'error'
			});
		} finally {
			saving = false;
		}
	}

	function handleProfileSkip() {
		console.log('[Setup] Skip clicked. Form values:', { firstName: firstName.trim(), lastName: lastName.trim(), username: username.trim() });
		currentStep = 'github';
		checkGitHubStatus();
	}

	function handleLinkGithub() {
		window.location.href = '/apiv1/github/link?redirect=' + encodeURIComponent('/setup');
	}

	function handleBack() {
		const idx = getStepIndex(currentStep);
		if (idx > 0) {
			currentStep = steps[idx - 1].key;
		}
	}

	function handleGithubSkip() {
		currentStep = 'done';
	}

	function handleGithubNext() {
		currentStep = 'done';
	}

	let completing = $state(false);

	async function handleComplete() {
		if (completing) return;
		completing = true;

		try {
			const invitations = [...$pendingInvitations];
			for (const invitation of invitations) {
				await pendingInvitations.accept(invitation.id, true);
			}

			const orgsResponse = await apiFetch('/apiv1/organizations/user');
			if (orgsResponse.ok) {
				const orgs = await orgsResponse.json();
				organizations.set(orgs);
				organizations.initializeSelected();
			}

			const response = await apiFetch('/apiv1/auth/me', {
				method: 'PATCH',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify({ setupCompleted: true })
			});

			if (response.ok) {
				const updatedUser = await response.json();
				user.set({ ...$user, ...updatedUser });
			} else {
				if ($user) user.set({ ...$user, setupCompleted: true });
			}

			goto('/', { replaceState: true });
		} catch {
			if ($user) user.set({ ...$user, setupCompleted: true });
			goto('/', { replaceState: true });
		} finally {
			completing = false;
		}
	}

	const steps: { key: Step; label: string }[] = [
		{ key: 'profile', label: 'Profile' },
		{ key: 'github', label: 'GitHub' },
		{ key: 'done', label: 'Done' }
	];

	function getStepIndex(step: Step): number {
		if (step === 'loading') return -1;
		return steps.findIndex((s) => s.key === step);
	}
</script>

