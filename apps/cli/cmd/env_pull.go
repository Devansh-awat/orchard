package cmd

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/LeafdTK/leaf/cli/internal/output"
	"github.com/spf13/cobra"
)

const pullHeader = "# Generated by `orchard env pull`"

var (
	sharedRefRe   = regexp.MustCompile(`\$\{\{\s*shared\.([A-Za-z_][A-Za-z0-9_]*)\s*\}\}`)
	bareDotenvVal = regexp.MustCompile(`^[A-Za-z0-9_./:@+,=-]+$`)
)

func envPullCmd() *cobra.Command {
	var out, deployment string
	var force bool
	c := &cobra.Command{
		Use:   "pull [env]",
		Short: "Write environment variables to a local dotenv file",
		Long: "Materializes the environment's shared variables into a local dotenv file for\n" +
			"development. Secret values are write-only on the server, so secret vars are\n" +
			"emitted as commented placeholders to fill in locally. With --deployment, that\n" +
			"deployment's own vars are merged on top with ${{shared.KEY}} references\n" +
			"resolved where the target is not secret.",
		Args: cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			cl, cfg, err := client()
			if err != nil {
				return err
			}
			explicit := ""
			if len(args) > 0 {
				explicit = args[0]
			}
			env, err := envScope(cmd.Context(), cl, cfg, explicit)
			if err != nil {
				return err
			}
			shared, err := envFetchVars(cmd.Context(), cl, pick(env, "id"))
			if err != nil {
				return err
			}

			type entry struct {
				key, value, note string
				secret           bool
			}
			byKey := map[string]*entry{}
			sharedVals := map[string]string{}
			sharedSecret := map[string]bool{}
			for _, v := range shared {
				k := str(v["key"])
				if k == "" {
					continue
				}
				sec := v["secret"] == true
				sharedVals[k], sharedSecret[k] = str(v["value"]), sec
				byKey[k] = &entry{key: k, value: str(v["value"]), secret: sec}
			}

			if deployment != "" {
				dvars, derr := deployFetchEnvVars(cmd.Context(), cl, deployment)
				if derr != nil {
					return derr
				}
				for _, v := range dvars {
					k := str(v["key"])
					if k == "" {
						continue
					}
					e := &entry{key: k, secret: v["secret"] == true}
					if !e.secret {
						val, ok := resolveSharedRefs(str(v["value"]), sharedVals, sharedSecret)
						if ok {
							e.value = val
						} else {
							e.secret = true
							e.note = "references a secret shared var"
						}
					}
					byKey[k] = e
				}
			}

			keys := make([]string, 0, len(byKey))
			for k := range byKey {
				keys = append(keys, k)
			}
			sort.Strings(keys)

			var b strings.Builder
			fmt.Fprintf(&b, "%s\n# environment %s (%s)\n", pullHeader, pick(env, "name"), pick(env, "id"))
			if deployment != "" {
				fmt.Fprintf(&b, "# merged with deployment %s\n", deployment)
			}
			fmt.Fprintf(&b, "# pulled %s. Do not commit this file.\n\n", time.Now().UTC().Format(time.RFC3339))

			secrets := 0
			for _, k := range keys {
				e := byKey[k]
				if e.secret {
					secrets++
					note := e.note
					if note == "" {
						note = "secret, value is write-only on the server; set it locally"
					}
					fmt.Fprintf(&b, "# %s= (%s)\n", e.key, note)
					continue
				}
				fmt.Fprintf(&b, "%s=%s\n", e.key, dotenvValue(e.value))
			}

			if existing, rerr := os.ReadFile(out); rerr == nil && !force && !strings.HasPrefix(string(existing), pullHeader) {
				return fmt.Errorf("%s exists and was not generated by orchard; pass --force to overwrite", out)
			}
			if err := os.WriteFile(out, []byte(b.String()), 0o600); err != nil {
				return err
			}

			output.Successf("wrote %d var(s) to %s", len(keys), out)
			if secrets > 0 {
				output.Warnf("%d secret var(s) are commented placeholders (values are write-only)", secrets)
			}
			if cwd, cerr := os.Getwd(); cerr == nil && !strings.Contains(out, "/") {
				if note := ensureGitignored(cwd, out); note != "" {
					output.Warnf("%s", note)
				}
			}
			return nil
		},
	}
	c.Flags().StringVar(&out, "out", ".env.orchard", "output file path")
	c.Flags().StringVar(&deployment, "deployment", "", "merge this deployment's own vars on top")
	c.Flags().BoolVar(&force, "force", false, "overwrite even if the file was not generated by orchard")
	return c
}

// resolveSharedRefs expands ${{shared.KEY}} references. Returns ok=false when
// any referenced var is secret (its value is unobtainable client-side).
func resolveSharedRefs(value string, vals map[string]string, secret map[string]bool) (string, bool) {
	ok := true
	res := sharedRefRe.ReplaceAllStringFunc(value, func(m string) string {
		key := sharedRefRe.FindStringSubmatch(m)[1]
		if secret[key] {
			ok = false
			return m
		}
		if v, exists := vals[key]; exists {
			return v
		}
		return ""
	})
	return res, ok
}

// dotenvValue quotes a value when it would not survive a round-trip as a bare
// dotenv token.
func dotenvValue(v string) string {
	if v == "" {
		return ""
	}
	if bareDotenvVal.MatchString(v) {
		return v
	}
	return strconv.Quote(v)
}
