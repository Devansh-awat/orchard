import { ForbiddenException, HttpException, HttpStatus } from '@nestjs/common';
import type { PrismaService } from '../prisma/prisma.service';
import { platformWildcardDomains } from './projects.utils';

export const DEFAULT_MAX_CUSTOM_DOMAINS_PER_ORG = 250;
export const DEFAULT_CUSTOM_DOMAIN_CREATES_PER_HOUR = 30;
export const FREE_PROOF_FAILURES = 5;
export const PROOF_BACKOFF_BASE_MS = 60_000;
export const PROOF_BACKOFF_MAX_MS = 24 * 60 * 60 * 1000;
export const PROOF_FAILURE_WINDOW_MS = 24 * 60 * 60 * 1000;
const CREATE_WINDOW_MS = 60 * 60 * 1000;

const ACTION_CREATE = 'custom_domain_create';
const FAILURE_KEY_PREFIX = 'domain_proof_failures:';
const TYPE = 'org';

export interface DomainBudgetLimits {
  maxCustomDomains: number;
  createsPerHour: number;
}

function limit(raw: string | undefined, fallback: number): number {
  const parsed = Number(raw?.trim());
  return raw?.trim() && Number.isInteger(parsed) && parsed >= 0 ? parsed : fallback;
}

export function domainBudgetLimits(env: NodeJS.ProcessEnv = process.env): DomainBudgetLimits {
  return {
    maxCustomDomains: limit(env.MAX_CUSTOM_DOMAINS_PER_ORG, DEFAULT_MAX_CUSTOM_DOMAINS_PER_ORG),
    createsPerHour: limit(
      env.MAX_CUSTOM_DOMAIN_CREATES_PER_HOUR,
      DEFAULT_CUSTOM_DOMAIN_CREATES_PER_HOUR
    )
  };
}

export function proofBackoffMs(failures: number): number {
  if (failures <= FREE_PROOF_FAILURES) return 0;
  const doublings = Math.min(failures - FREE_PROOF_FAILURES - 1, 20);
  return Math.min(PROOF_BACKOFF_BASE_MS * 2 ** doublings, PROOF_BACKOFF_MAX_MS);
}

export function isPlatformHost(host: string): boolean {
  return platformWildcardDomains().some((wildcard) => host.endsWith(wildcard.suffix));
}

function tooMany(message: string, retryAfterSeconds: number): HttpException {
  return new HttpException(
    { statusCode: HttpStatus.TOO_MANY_REQUESTS, message, retryAfter: retryAfterSeconds },
    HttpStatus.TOO_MANY_REQUESTS
  );
}

function minutes(ms: number): number {
  return Math.max(1, Math.ceil(ms / 60_000));
}

export class DomainBudget {
  constructor(
    private readonly prisma: PrismaService,
    private readonly env: NodeJS.ProcessEnv = process.env,
    private readonly now: () => Date = () => new Date()
  ) {}

  private async readFailures(
    organizationId: string
  ): Promise<{ count: number; windowStart: number; blockedUntil: number } | null> {
    const row = await this.prisma.instanceSetting.findUnique({
      where: { key: `${FAILURE_KEY_PREFIX}${organizationId}` }
    });
    if (!row) return null;
    try {
      const parsed = JSON.parse(row.value);
      return {
        count: Number(parsed.count) || 0,
        windowStart: Number(parsed.windowStart) || 0,
        blockedUntil: Number(parsed.blockedUntil) || 0
      };
    } catch {
      return null;
    }
  }

  async assertProofNotPaused(organizationId: string): Promise<void> {
    const record = await this.readFailures(organizationId);
    const now = this.now().getTime();
    if (record && record.blockedUntil > now) {
      const wait = record.blockedUntil - now;
      throw tooMany(
        `Too many domain checks failed. Try again in ${minutes(wait)} minutes.`,
        Math.ceil(wait / 1000)
      );
    }
  }

  async recordProofFailure(organizationId: string): Promise<void> {
    const now = this.now().getTime();
    const record = await this.readFailures(organizationId);
    const fresh = !record || now - record.windowStart > PROOF_FAILURE_WINDOW_MS;
    const count = fresh ? 1 : record.count + 1;
    const backoff = proofBackoffMs(count);
    const value = JSON.stringify({
      count,
      windowStart: fresh ? now : record.windowStart,
      blockedUntil: backoff > 0 ? now + backoff : 0
    });
    const key = `${FAILURE_KEY_PREFIX}${organizationId}`;
    await this.prisma.instanceSetting.upsert({
      where: { key },
      create: { key, value },
      update: { value }
    });
  }

  async clearProofFailures(organizationId: string): Promise<void> {
    await this.prisma.instanceSetting.deleteMany({
      where: { key: `${FAILURE_KEY_PREFIX}${organizationId}` }
    });
  }

  async assertCapacity(organizationId: string): Promise<void> {
    const cap = domainBudgetLimits(this.env).maxCustomDomains;
    if (cap === 0) return;
    const rows = await this.prisma.ingress.findMany({
      where: { project: { organizationId }, isAutoGenerated: false },
      select: { host: true },
      distinct: ['host']
    });
    const used = rows.filter((row) => !isPlatformHost(row.host.toLowerCase())).length;
    if (used >= cap) {
      throw new ForbiddenException(
        `This organization already has ${used} custom domains (limit ${cap}). Remove one before adding another.`
      );
    }
  }

  async consumeCreate(organizationId: string): Promise<void> {
    const cap = domainBudgetLimits(this.env).createsPerHour;
    if (cap === 0) return;
    const now = this.now();
    const key = {
      identifier_type_action: {
        identifier: organizationId,
        type: TYPE,
        action: ACTION_CREATE
      }
    };
    const record = await this.prisma.rateLimitRecord.findUnique({ where: key });
    if (!record) {
      await this.prisma.rateLimitRecord.create({
        data: {
          identifier: organizationId,
          type: TYPE,
          action: ACTION_CREATE,
          count: 1,
          windowStart: now
        }
      });
      return;
    }
    const age = now.getTime() - record.windowStart.getTime();
    if (age > CREATE_WINDOW_MS) {
      await this.prisma.rateLimitRecord.update({
        where: key,
        data: { count: 1, windowStart: now, blockedUntil: null }
      });
      return;
    }
    if (record.count >= cap) {
      const wait = CREATE_WINDOW_MS - age;
      throw tooMany(
        `This organization added too many custom domains in the last hour. Try again in ${minutes(wait)} minutes.`,
        Math.ceil(wait / 1000)
      );
    }
    await this.prisma.rateLimitRecord.update({ where: key, data: { count: { increment: 1 } } });
  }
}
