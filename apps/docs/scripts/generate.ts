/**
 * Regenerates every reference page that has a machine-readable source, so the
 * docs cannot drift from the code. Run with `pnpm --filter docs generate`.
 *
 *   MCP tools   <- apps/server/src/mcp/tools/*.ts  (registered against a stub server)
 *   CLI         <- apps/cli                        (cobra's own markdown tree)
 *   Config      <- .env.example                    (comment blocks become descriptions)
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zodToJsonSchema } from 'zod-to-json-schema';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '../../..');
const outDir = resolve(here, '../src/content/docs/reference');

const BANNER = '{/* Generated by scripts/generate.ts. Do not edit by hand. */}\n\n';

function write(name: string, body: string) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, name), body);
  console.log(`  wrote reference/${name} (${body.length} bytes)`);
}

function fence(lang: string, body: string) {
  return '```' + lang + '\n' + body + '\n```';
}

/**
 * MDX treats `<word>` as a JSX tag, and CLI help is full of `<account-id>`
 * style placeholders. Anything interpolated outside a code fence goes through
 * here: angle brackets become entities, pipes are escaped for tables.
 */
function esc(text: unknown): string {
  return String(text ?? '')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\|/g, '\\|')
    .replace(/\{/g, '&#123;')
    .replace(/\}/g, '&#125;')
    .trim();
}

/* ------------------------------------------------------------------ MCP --- */

type Registered = {
  name: string;
  group: string;
  description: string;
  annotations: Record<string, unknown>;
  input: Record<string, unknown> | null;
};

async function generateMcp() {
  const toolsDir = resolve(repoRoot, 'apps/server/src/mcp/tools');
  const collected: Registered[] = [];
  let group = '';

  // Stub that captures registerTool calls instead of serving them.
  const server = {
    registerTool(name: string, config: any) {
      let input: Record<string, unknown> | null = null;
      if (config?.inputSchema) {
        try {
          const { z } = require('zod');
          input = zodToJsonSchema(z.object(config.inputSchema)) as Record<string, unknown>;
        } catch {
          input = null;
        }
      }
      collected.push({
        name,
        group,
        description: String(config?.description ?? '').trim(),
        annotations: config?.annotations ?? {},
        input
      });
    },
    tool(name: string, description: string) {
      collected.push({
        name,
        group,
        description,
        annotations: {},
        input: null
      });
    }
  };

  // The client is only used inside handlers, which we never invoke.
  const client = new Proxy({}, { get: () => () => undefined });

  const files = readdirSync(toolsDir)
    .filter((f) => f.endsWith('.ts'))
    .sort();

  for (const file of files) {
    group = file.replace(/\.ts$/, '');
    const mod = await import(join(toolsDir, file));
    for (const [key, fn] of Object.entries(mod)) {
      if (typeof fn === 'function' && /^register.*Tools$/.test(key)) {
        (fn as Function)(server, client);
      }
    }
  }

  collected.sort((a, b) => a.name.localeCompare(b.name));

  const groups = [...new Set(collected.map((t) => t.group))].sort();
  let body = `---
title: MCP tools
description: Every Model Context Protocol tool Orchard exposes, generated from the server's tool registry.
sidebar:
  order: 2
---

${BANNER.trim()}

Orchard exposes **${collected.length} MCP tools** across ${groups.length} groups. Point any MCP
client at \`https://your-orchard/mcp\` and these are the calls it can make. Every tool
runs as the user who authorised the connection, so the same permissions apply.

`;

  for (const g of groups) {
    const tools = collected.filter((t) => t.group === g);
    body += `## ${g}\n\n`;
    for (const t of tools) {
      const hints: string[] = [];
      if (t.annotations.readOnlyHint) hints.push('read-only');
      if (t.annotations.destructiveHint) hints.push('destructive');
      if (t.annotations.idempotentHint) hints.push('idempotent');

      body += `### \`${t.name}\`\n\n`;
      if (hints.length) body += `**${hints.join(' · ')}**\n\n`;
      if (t.description) body += `${esc(t.description)}\n\n`;

      const props = (t.input as any)?.properties ?? {};
      const required: string[] = (t.input as any)?.required ?? [];
      const names = Object.keys(props);
      if (names.length) {
        body += `| Parameter | Type | Required | Description |\n| --- | --- | --- | --- |\n`;
        for (const p of names) {
          const spec = props[p] ?? {};
          const type = spec.type
            ? Array.isArray(spec.type)
              ? spec.type.join(' \\| ')
              : spec.type
            : spec.anyOf
              ? 'any'
              : 'object';
          const desc = esc(spec.description);
          body += `| \`${p}\` | ${type} | ${required.includes(p) ? 'yes' : 'no'} | ${desc} |\n`;
        }
        body += '\n';
      }
    }
  }

  write('mcp-tools.mdx', body);
  return collected.length;
}

/* ------------------------------------------------------------------ CLI --- */

type CliFlag = {
  name: string;
  shorthand?: string;
  type: string;
  default: string;
  usage: string;
  persistent: boolean;
};

type CliCommand = {
  name: string;
  short: string;
  use: string;
  aliases?: string[];
  hidden?: boolean;
  flags: CliFlag[];
};

function generateCli() {
  const cliDir = resolve(repoRoot, 'apps/cli');

  // The CLI dumps its own command tree: no auth, no network, no scraping.
  let commands: CliCommand[] = [];
  try {
    const json = execFileSync('go', ['run', '.', 'commands', '-o', 'json'], {
      cwd: cliDir,
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 32 * 1024 * 1024
    }).toString();
    commands = JSON.parse(json);
  } catch (err: any) {
    console.log('  ! could not run the CLI dump (' + String(err.message).split('\n')[0] + ')');
    return 0;
  }

  const visible = commands
    .filter((c) => !c.hidden && c.name)
    .sort((a, b) => a.name.localeCompare(b.name));

  // Group by first path segment so the page reads as one section per topic.
  const groups = new Map<string, CliCommand[]>();
  for (const c of visible) {
    const top = c.name.split(' ')[0];
    if (!groups.has(top)) groups.set(top, []);
    groups.get(top)!.push(c);
  }

  let body = `---
title: CLI reference
description: Every orchard CLI command, generated from the binary's own command tree.
sidebar:
  order: 1
---

${BANNER.trim()}

The \`orchard\` CLI speaks the same API as the dashboard. Output is human-readable in a
terminal and JSON when piped, so your scripts get the same powers you do.

${fence('bash', 'brew install --cask leafdtk/tap/orchard-cli')}

Every command accepts \`-o json\` for machine-readable output, and \`--org\` / \`--env\` to
override the saved context. **${visible.length} commands** are available.

`;

  for (const [top, cmds] of [...groups.entries()].sort()) {
    body += `## ${top}\n\n`;
    for (const c of cmds) {
      body += `### \`orchard ${c.name}\`\n\n`;
      if (c.short) body += `${esc(c.short)}\n\n`;
      body += `${fence('bash', 'orchard ' + c.use)}\n\n`;
      if (c.aliases?.length) body += `Aliases: ${c.aliases.map((a) => `\`${a}\``).join(', ')}\n\n`;

      const own = c.flags?.filter((f) => !f.persistent) ?? [];
      if (own.length) {
        body += `| Flag | Type | Default | Description |\n| --- | --- | --- | --- |\n`;
        for (const f of own) {
          const flag = f.shorthand ? `\`-${f.shorthand}\`, \`--${f.name}\`` : `\`--${f.name}\``;
          const def = f.default ? `\`${esc(f.default)}\`` : '';
          body += `| ${flag} | ${f.type} | ${def} | ${esc(f.usage)} |\n`;
        }
        body += '\n';
      }
    }
  }

  write('cli.mdx', body);
  return visible.length;
}

/* --------------------------------------------------------------- config --- */

function generateConfig() {
  const raw = readFileSync(resolve(repoRoot, '.env.example'), 'utf8');
  const lines = raw.split('\n');

  type Entry = { key: string; value: string; notes: string[]; section: string };
  const entries: Entry[] = [];
  let notes: string[] = [];
  let section = 'General';

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      notes = [];
      continue;
    }
    if (trimmed.startsWith('#')) {
      const text = trimmed.replace(/^#+\s?/, '');
      // A banner line (===, ---, or ALL CAPS heading) starts a new section.
      if (/^[-=]{3,}$/.test(text)) continue;
      if (/^[A-Z0-9 ,&/()'-]{4,}$/.test(text) && !text.includes('=')) {
        section = text
          .toLowerCase()
          .replace(/\b\w/g, (c) => c.toUpperCase())
          .trim();
        notes = [];
        continue;
      }
      notes.push(text);
      continue;
    }
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    entries.push({
      key: trimmed.slice(0, eq).trim(),
      value: trimmed.slice(eq + 1).trim(),
      notes: [...notes],
      section
    });
    notes = [];
  }

  const sections = [...new Set(entries.map((e) => e.section))];
  let body = `---
title: Configuration
description: Every environment variable the Orchard server reads, generated from .env.example.
sidebar:
  order: 3
---

${BANNER.trim()}

Orchard reads its configuration from the environment. ${entries.length} variables are
recognised. Anything without a default is optional unless the description says otherwise.

`;

  for (const s of sections) {
    const rows = entries.filter((e) => e.section === s);
    if (!rows.length) continue;
    body += `## ${s}\n\n| Variable | Default | Description |\n| --- | --- | --- |\n`;
    for (const e of rows) {
      const def = e.value ? `\`${esc(e.value)}\`` : '';
      const desc = esc(e.notes.join(' '));
      body += `| \`${e.key}\` | ${def} | ${desc} |\n`;
    }
    body += '\n';
  }

  write('configuration.mdx', body);
  return entries.length;
}

/* -------------------------------------------------------------- openapi --- */

/**
 * starlight-openapi builds one page per operation from the path, and the
 * contract contains a bare "/" route whose slug comes out empty. Emit a
 * sanitised copy for the docs rather than changing the published contract.
 */
function generateOpenApi() {
  const src = resolve(repoRoot, 'packages/contracts/openapi.json');
  const spec = JSON.parse(readFileSync(src, 'utf8'));
  const before = Object.keys(spec.paths ?? {}).length;

  for (const path of Object.keys(spec.paths ?? {})) {
    if (!path || path.trim() === '' || path === '/') delete spec.paths[path];
  }

  const after = Object.keys(spec.paths ?? {}).length;
  const dest = resolve(here, '../openapi.generated.json');
  writeFileSync(dest, JSON.stringify(spec, null, 2) + '\n');
  if (before !== after) console.log(`  dropped ${before - after} unroutable path(s) from the spec`);
  console.log(`  wrote openapi.generated.json (${after} paths)`);
  return after;
}

/* ----------------------------------------------------------------- main --- */

console.log('generating reference docs...');
const mcpCount = await generateMcp();
const cliPages = generateCli();
const envCount = generateConfig();
const apiPaths = generateOpenApi();
console.log(
  `done: ${mcpCount} MCP tools, ${cliPages} CLI commands, ${envCount} config variables, ${apiPaths} API paths`
);
